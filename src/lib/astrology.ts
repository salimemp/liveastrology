// Simplified Moon Sign Calculation
// This is an approximation - real calculation requires ephemeris data
export function calculateMoonSign(birthDate: Date, birthTime: string): { sign: ZodiacSignName; degree: number } {
  // Get base day and time
  const dayOfYear = getDayOfYear(birthDate);
  const [hours, minutes] = birthTime.split(':').map(Number);
  const totalMinutes = hours * 60 + minutes;

  // Moon moves approximately 13 degrees per day
  // We'll use a simplified calculation based on day and time
  const baseMoonPosition = (dayOfYear * 13) % 360;
  const timeAdjustment = (totalMinutes / 1440) * 13;
  const moonPosition = (baseMoonPosition + timeAdjustment + 180) % 360; // Add offset for moon phase

  // Convert position to sign (each sign is 30 degrees)
  const signIndex = Math.floor(moonPosition / 30);
  const degreeInSign = Math.round(moonPosition % 30);

  const signs: ZodiacSignName[] = ['aries', 'taurus', 'gemini', 'cancer', 'leo', 'virgo', 'libra', 'scorpio', 'sagittarius', 'capricorn', 'aquarius', 'pisces'];

  return { sign: signs[signIndex], degree: degreeInSign };
}

// Simplified Rising Sign (Ascendant) Calculation
// This requires exact birth time and location
export function calculateRisingSign(birthDate: Date, birthTime: string, latitude: number): { sign: ZodiacSignName; degree: number } {
  const dayOfYear = getDayOfYear(birthDate);
  const [hours, minutes] = birthTime.split(':').map(Number);
  const totalHours = hours + minutes / 60;

  // Simplified ascendant calculation
  // The ascendant changes roughly every 2 hours
  // This is a basic approximation

  // Base ascendant position based on time of day
  const baseAscendant = (totalHours * 15) % 360; // 15 degrees per hour

  // Adjust for latitude (simplified)
  const latAdjustment = latitude * 0.5;

  // Seasonal adjustment
  const seasonalFactor = Math.sin((dayOfYear - 81) * Math.PI / 182.5) * 10;

  // Calculate final ascendant
  const ascendant = (baseAscendant + latAdjustment + seasonalFactor + 90) % 360;

  const signIndex = Math.floor(ascendant / 30);
  const degreeInSign = Math.round(ascendant % 30);

  const signs: ZodiacSignName[] = ['aries', 'taurus', 'gemini', 'cancer', 'leo', 'virgo', 'libra', 'scorpio', 'sagittarius', 'capricorn', 'aquarius', 'pisces'];

  return { sign: signs[signIndex], degree: degreeInSign };
}

