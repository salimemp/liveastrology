// Calculate element balance
function calculateElementBalance(sun: Sign, moon: Sign, rising: Sign): ElementBalance {
  const signs = [sun, moon, rising];
  const counts = { fire: 0, earth: 0, air: 0, water: 0 };

  signs.forEach(sign => {
    counts[sign.element]++;
  });

  return {
    fire: Math.round((counts.fire / 3) * 100),
    earth: Math.round((counts.earth / 3) * 100),
    air: Math.round((counts.air / 3) * 100),
    water: Math.round((counts.water / 3) * 100)
  };
}

// Calculate modality balance
function calculateModalityBalance(sun: Sign, moon: Sign, rising: Sign): ModalityBalance {
  const signs = [sun, moon, rising];
  const counts = { cardinal: 0, fixed: 0, mutable: 0 };

  signs.forEach(sign => {
    counts[sign.modality]++;
  });

  return {
    cardinal: Math.round((counts.cardinal / 3) * 100),
    fixed: Math.round((counts.fixed / 3) * 100),
    mutable: Math.round((counts.mutable / 3) * 100)
  };
}

// Calculate compatibility based on elements
function calculateCompatibility(sun: Sign): CompatibilityInfo {
  const elementMap: Record<string, string[]> = {
    fire: ['fire', 'air'],
    earth: ['earth', 'water'],
    air: ['air', 'fire'],
    water: ['water', 'earth']
  };

  const allSigns = Object.keys(ZODIAC_SIGNS) as ZodiacSignName[];

  const compatible: string[] = [];
  const friendshipCompatible: string[] = [];
  const challenging: string[] = [];

  allSigns.forEach(signName => {
    const sign = ZODIAC_SIGNS[signName];
    const compatibleElements = elementMap[sun.element];

    if (compatibleElements.includes(sign.element)) {
      if (sign.element === sun.element) {
        compatible.push(sign.name);
      } else {
        friendshipCompatible.push(sign.name);
      }
    }

    // Challenging: opposite elements
    if ((sun.element === 'fire' && sign.element === 'water') ||
        (sun.element === 'earth' && sign.element === 'air') ||
        (sun.element === 'air' && sign.element === 'earth') ||
        (sun.element === 'water' && sign.element === 'fire')) {
      challenging.push(sign.name);
    }
  });

  return {
    bestMatches: compatible.slice(0, 4),
    friendshipMatches: friendshipCompatible.slice(0, 4),
    challengingMatches: challenging.slice(0, 4)
  };
}

// Main calculation function
export function calculateAstrology(birthData: BirthData): AstrologyResult {
  const { date, time, location } = birthData;

  // Calculate all three signs
  const sunCalc = calculateSunSign(date);
  const moonCalc = calculateMoonSign(date, time);
  const risingCalc = calculateRisingSign(date, time, location.latitude);

  const sun = createSign(sunCalc.sign, sunCalc.degree);
  const moon = createSign(moonCalc.sign, moonCalc.degree);
  const rising = createSign(risingCalc.sign, risingCalc.degree);

  return {
    sun,
    moon,
    rising,
    elementBalance: calculateElementBalance(sun, moon, rising),
    modalityBalance: calculateModalityBalance(sun, moon, rising),
    compatibility: calculateCompatibility(sun),
    birthChart: {
      date: date.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' }),
      time: formatTime(time),
      location: location.name
    }
  };
}

// Format time for display
export function formatTime(time: string): string {
  const [hours, minutes] = time.split(':').map(Number);
  const period = hours >= 12 ? 'PM' : 'AM';
  const displayHours = hours % 12 || 12;
  return `${displayHours}:${minutes.toString().padStart(2, '0')} ${period}`;
}

